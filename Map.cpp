#include "Map.h"

// '#' = wall, '.' = empty
static const char* MAP[MAP_H] =
{
    "################",
    "#..............#",
    "#..##......##..#",
    "#..#........#..#",
    "#..............#",
    "#.....####.....#",
    "#.....#..#.....#",
    "#.....#..#.....#",
    "#..............#",
    "#..#........#..#",
    "#..##......##..#",
    "#..............#",
    "#......##......#",
    "#..............#",
    "#..............#",
    "################",
};

bool IsWall(int x, int y)
{
    if (x < 0 || y < 0 || x >= MAP_W || y >= MAP_H) return true;
    return MAP[y][x] == '#';
}